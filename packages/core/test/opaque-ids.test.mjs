import assert from 'node:assert/strict';
import test from 'node:test';
import {BoardApi} from '../dist/api.js';
import {fakeSkrynia} from './fake-skrynia.mjs';
test('random opaque IDs survive all basic board operations and reload',async()=>{
 const server=fakeSkrynia();
 const mk=(opts={})=>new BoardApi({fetch:server.fetch.bind(server),...opts});
 const client=mk();
 const init=await client.initialize();
 const a=await client.createIssue('A');
 const b=await client.createIssue('B');
 const id=a.number,id2=b.number;
 assert.match(id,/^[A-Za-z0-9]{22}-[a-z]+$/);
 assert.notEqual(id,id2);
 assert.equal((await client.getIssue(id)).number,id);
 assert.deepEqual(await client.getQueue(),[id,id2]);
 assert.deepEqual(await client.reorderQueue([id2,id]),[id2,id]);
 const res=await client.comment(id,'human','hi');
 assert.equal(res.messages[0].body,'hi');
 assert.equal((await client.getIssuePage(id,1)).messages[0].body,'hi');
 assert.equal((await client.getIssueCommentPage(id,1)).messages[0].body,'hi');
 await client.editIssueBody(id,'updated');
 assert.equal((await client.getIssue(id)).body,'updated');
 await client.close(id);
 assert.equal((await client.getIssue(id)).state,'closed');
 await client.reopen(id);
 const resource=await client.addResourceDependency('lubko://example-host','/workspace/task',id);
 assert.deepEqual(resource.issueNumbers,[id]);
 assert.equal((await client.listResources(undefined,id))[0].issues[0].number,id);
 const fresh=mk({credential:init.credential,trustAnchor:init.trustAnchor});
 assert.equal((await fresh.getIssue(id)).number,id);
 await fresh.deleteIssue(id);
 await assert.rejects(()=>fresh.getIssue(id),/does not exist/);
 assert.deepEqual(await fresh.getQueue(),[id2]);
});